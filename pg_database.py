"""PostgreSQL adapter for the existing CliMa SQL API; no HTTP SQL endpoint."""
import os,re,sqlite3,base64
ID_TABLES=set('users staff requests messages cases case_entries notices schedules audit attachments appointments privacy_requests consent_events devices push_outbox admin_changes'.split())
class Cursor:
 def __init__(self,cur,factory):
  self.rowcount=cur.rowcount;self.description=cur.description;self.lastrowid=None
  self.rows=[factory(self,row) for row in cur.fetchall()] if cur.description else []
 def fetchone(self):return self.rows.pop(0) if self.rows else None
 def fetchall(self):rows=self.rows;self.rows=[];return rows
 def __iter__(self):return iter(self.fetchall())
def convert(sql):
 sql=re.sub(r'\bINTEGER PRIMARY KEY\b','BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',sql,flags=re.I)
 sql=re.sub(r'\bREAL\b','DOUBLE PRECISION',sql,flags=re.I)
 sql=re.sub(r'\bage INTEGER\b','age TEXT',sql,flags=re.I)
 sql=sql.replace('MAX(value,','GREATEST(value,')
 sql=sql.replace('WHEN reset<','WHEN login_limits.reset<').replace('ELSE count+1','ELSE login_limits.count+1').replace('ELSE reset END','ELSE login_limits.reset END')
 sql=sql.replace("datetime('now','-24 hours')","to_char(CURRENT_TIMESTAMP - interval '24 hours','YYYY-MM-DD HH24:MI:SS')")
 sql=sql.replace("datetime('now',?)","to_char(CURRENT_TIMESTAMP + CAST(? AS interval),'YYYY-MM-DD HH24:MI:SS')")
 ignore=bool(re.match(r'\s*INSERT OR IGNORE\b',sql,re.I));sql=re.sub(r'INSERT OR IGNORE','INSERT',sql,flags=re.I)
 if ignore:sql=sql.rstrip().rstrip(';')+' ON CONFLICT DO NOTHING'
 # Question marks inside quoted SQL literals must remain literal.
 pieces=re.split("('(?:''|[^'])*')",sql)
 return ''.join(p.replace('%','%%') if i%2 else p.replace('%','%%').replace('?','%s') for i,p in enumerate(pieces))
class Connection:
 postgres=True
 def __init__(self,url,factory):
  import psycopg
  from urllib.parse import urlsplit
  if urlsplit(url).port==6543:raise ValueError('Use Supabase session pooler port 5432, not transaction pooling')
  for attempt in range(3):
   try:
    self.raw=psycopg.connect(url,connect_timeout=10,sslmode=os.getenv('CLIMA_PG_SSLMODE','verify-full'),sslrootcert=__import__('certifi').where(),prepare_threshold=None);break
   except psycopg.OperationalError:
    if attempt==2:raise
    __import__('time').sleep(0.1)
  self.factory=factory
  self.raw.execute('SET search_path TO clima, extensions, public')
  self.raw.execute("SELECT set_config('clima.data_key',%s,false)",(base64.urlsafe_b64decode(os.environ['CLIMA_DATA_KEY']).hex(),))
  self.raw.execute("SET statement_timeout='25s'")
 def execute(self,sql,args=()):
  m=re.fullmatch(r'PRAGMA table_info\((\w+)\)',sql,re.I)
  if m:return self.execute("SELECT column_name AS name FROM information_schema.columns WHERE table_schema='clima' AND table_name=?",(m[1],))
  translated=convert(sql);m=re.match(r'\s*INSERT INTO (\w+)\b',translated,re.I)
  ident=m and m[1] in ID_TABLES
  if ident:translated=translated.rstrip().rstrip(';')+' RETURNING id'
  try:
   cur=self.raw.execute(translated,tuple(args));result=Cursor(cur,self.factory)
   if ident and result.rows:result.lastrowid=result.rows[0]['id']
   return result
  except __import__('psycopg').IntegrityError as e:raise sqlite3.IntegrityError('Database constraint') from e
  except Exception:
   if os.getenv('CLIMA_TEST_POSTGRES'):
    import traceback;traceback.print_exc()
   raise
 def executescript(self,script):
  for statement in script.split(';'):
   if statement.strip():self.execute(statement)
 def commit(self):self.raw.commit()
 def rollback(self):self.raw.rollback()
 def close(self):self.raw.close()
 def __enter__(self):return self
 def __exit__(self,typ,value,tb):
  try:self.raw.rollback() if typ else self.raw.commit()
  finally:self.raw.close()
 def encryption(self,fields):
  for table,columns in fields.items():
   # Function and trigger definitions are generated from the fixed application field list.
   self.raw.execute(f'DROP TRIGGER IF EXISTS encrypt_fields ON {table}')
   params=','.join("'"+x+"'" for x in columns)
   self.raw.execute(f'CREATE TRIGGER encrypt_fields BEFORE INSERT OR UPDATE ON {table} FOR EACH ROW EXECUTE FUNCTION clima.encrypt_fields({params})')
   self.raw.execute(f'UPDATE {table} SET '+','.join(c+'='+c for c in columns))
